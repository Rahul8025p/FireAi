"""
LLM-compiled tax engine for FY 2024-25.
Rules were generated ONCE by an LLM, reviewed, stored as Python code.
At runtime, NO LLM calls are made — it runs pure Python logic.
"""
from __future__ import annotations
import os
from implementations.hand_coded_rules import (
    TaxInput, TaxResult, RegimeTaxResult, SlabDetail, _result_to_dict,
    OLD_STANDARD_DEDUCTION, NEW_STANDARD_DEDUCTION,
    LIMIT_80C, LIMIT_80CCD1B, LIMIT_80D_SELF_NORMAL, LIMIT_80D_SELF_SENIOR,
    LIMIT_80D_PARENTS_NORMAL, LIMIT_80D_PARENTS_SENIOR, LIMIT_HOME_LOAN,
    OLD_REBATE_INCOME_LIMIT, OLD_REBATE_MAX, NEW_REBATE_INCOME_LIMIT, NEW_REBATE_MAX,
    NEW_REGIME_SURCHARGE_CAP,
)


# ─── LLM-generated compiled rules ────────────────────────────────────────────
# The following functions were generated by an LLM (Gemini) in one offline
# compilation step, reviewed for correctness, and stored here.
# They implement the EXACT same logic as hand_coded_rules.py.


def _llm_gen_slab_tax(income: int, slabs: list[tuple]) -> tuple[int, list[dict]]:
    """LLM-generated: compute slab-wise tax and return (total, details)."""
    total = 0
    details = []
    for (lo, hi, rate) in slabs:
        if income <= lo:
            break
        taxable_in_slab = min(income, hi if hi is not None else income) - lo
        if taxable_in_slab <= 0:
            continue
        tax = int(taxable_in_slab * rate)
        total += tax
        details.append({
            "slab_start": lo,
            "slab_end": hi,
            "rate": rate,
            "income_in_slab": taxable_in_slab,
            "tax_in_slab": tax,
        })
    return total, details


def _llm_gen_hra(gross: int, hra_recv: int, rent: int, metro: bool) -> int:
    """LLM-generated: compute HRA exemption per Income Tax Act rules."""
    if rent == 0 or hra_recv == 0:
        return 0
    basic = int(gross * 0.50)
    pct = 0.50 if metro else 0.40
    limit_a = hra_recv
    limit_b = max(0, rent - int(basic * 0.10))
    limit_c = int(basic * pct)
    return min(limit_a, limit_b, limit_c)


def _llm_gen_surcharge(income: int, tax: int, new_regime: bool) -> tuple[float, int, int]:
    """LLM-generated: compute surcharge and marginal relief."""
    if income <= 5_000_000:
        return 0.0, 0, 0

    # Determine bracket and threshold
    brackets = [
        (5_000_000, 10_000_000, 0.10),
        (10_000_000, 20_000_000, 0.15),
        (20_000_000, 50_000_000, 0.25),
        (50_000_000, None, 0.37),
    ]
    rate = 0.0
    threshold = 5_000_000
    for lo, hi, r in brackets:
        if income > lo:
            rate = r
            threshold = lo
        else:
            break

    if new_regime:
        rate = min(rate, NEW_REGIME_SURCHARGE_CAP)

    surcharge = int(tax * rate)

    # Marginal relief
    old_slabs = [
        (0, 250_000, 0.00),
        (250_000, 500_000, 0.05),
        (500_000, 1_000_000, 0.20),
        (1_000_000, None, 0.30),
    ]
    new_slabs = [
        (0, 300_000, 0.00),
        (300_000, 700_000, 0.05),
        (700_000, 1_000_000, 0.10),
        (1_000_000, 1_200_000, 0.15),
        (1_200_000, 1_500_000, 0.20),
        (1_500_000, None, 0.30),
    ]
    slabs = new_slabs if new_regime else old_slabs
    tax_at_threshold, _ = _llm_gen_slab_tax(threshold, slabs)

    # Surcharge at threshold bracket (prior bracket)
    threshold_rate = 0.0
    for lo, hi, r in brackets:
        if threshold > lo:
            threshold_rate = min(r, NEW_REGIME_SURCHARGE_CAP) if new_regime else r
        else:
            break

    tax_at_thr_total = int(tax_at_threshold * (1 + threshold_rate))
    max_allowed = tax_at_thr_total + (income - threshold)
    actual = tax + surcharge
    relief = max(0, actual - max_allowed)
    surcharge = max(0, surcharge - relief)
    return rate, surcharge, relief


def _llm_gen_old_regime(inp: TaxInput) -> RegimeTaxResult:
    """LLM-generated: old regime tax computation."""
    std = OLD_STANDARD_DEDUCTION
    hra = _llm_gen_hra(inp.annual_salary, inp.hra_received, inp.actual_rent_paid, inp.is_metro)
    c80c = min(inp.investment_80c, LIMIT_80C)
    c80ccd = min(inp.investment_80ccd1b, LIMIT_80CCD1B)
    self_limit = LIMIT_80D_SELF_SENIOR if inp.age >= 60 else LIMIT_80D_SELF_NORMAL
    parents_limit = LIMIT_80D_PARENTS_SENIOR if inp.parents_senior_citizen else LIMIT_80D_PARENTS_NORMAL
    d_self = min(inp.medical_80d_self, self_limit)
    d_par = min(inp.medical_80d_parents, parents_limit)
    d_home = min(inp.home_loan_interest, LIMIT_HOME_LOAN)
    total_ded = std + hra + c80c + c80ccd + d_self + d_par + d_home
    taxable = max(0, inp.annual_salary - total_ded)

    old_slabs = [
        (0, 250_000, 0.00),
        (250_000, 500_000, 0.05),
        (500_000, 1_000_000, 0.20),
        (1_000_000, None, 0.30),
    ]
    gross_tax, slab_dicts = _llm_gen_slab_tax(taxable, old_slabs)

    rebate = 0
    if taxable <= OLD_REBATE_INCOME_LIMIT:
        rebate = min(gross_tax, OLD_REBATE_MAX)

    tax_ar = gross_tax - rebate
    s_rate, surcharge, relief = _llm_gen_surcharge(taxable, tax_ar, False)
    cess = int((tax_ar + surcharge) * 0.04)
    final = tax_ar + surcharge + cess

    slab_details = [
        SlabDetail(
            slab_start=s["slab_start"], slab_end=s["slab_end"],
            rate=s["rate"], income_in_slab=s["income_in_slab"],
            tax_in_slab=s["tax_in_slab"],
        )
        for s in slab_dicts
    ]

    return RegimeTaxResult(
        regime="old", gross_salary=inp.annual_salary,
        standard_deduction=std, hra_exemption=hra,
        deduction_80c=c80c, deduction_80ccd1b=c80ccd,
        deduction_80d_self=d_self, deduction_80d_parents=d_par,
        deduction_home_loan=d_home, total_deductions=total_ded,
        taxable_income=taxable, slab_details=slab_details,
        gross_tax=gross_tax, rebate_87a=rebate,
        tax_after_rebate=tax_ar, surcharge_rate=s_rate,
        surcharge=surcharge, marginal_relief=relief,
        surcharge_after_relief=surcharge, cess=cess, final_tax=final,
        notes=["LLM-compiled rule execution"],
    )


def _llm_gen_new_regime(inp: TaxInput) -> RegimeTaxResult:
    """LLM-generated: new regime tax computation."""
    std = NEW_STANDARD_DEDUCTION
    taxable = max(0, inp.annual_salary - std)

    new_slabs = [
        (0, 300_000, 0.00),
        (300_000, 700_000, 0.05),
        (700_000, 1_000_000, 0.10),
        (1_000_000, 1_200_000, 0.15),
        (1_200_000, 1_500_000, 0.20),
        (1_500_000, None, 0.30),
    ]
    gross_tax, slab_dicts = _llm_gen_slab_tax(taxable, new_slabs)

    rebate = 0
    if taxable <= NEW_REBATE_INCOME_LIMIT:
        rebate = min(gross_tax, NEW_REBATE_MAX)
    elif taxable > 700_000 and gross_tax > (taxable - 700_000):
        rebate = gross_tax - (taxable - 700_000)

    tax_ar = gross_tax - rebate
    s_rate, surcharge, relief = _llm_gen_surcharge(taxable, tax_ar, True)
    cess = int((tax_ar + surcharge) * 0.04)
    final = tax_ar + surcharge + cess

    slab_details = [
        SlabDetail(
            slab_start=s["slab_start"], slab_end=s["slab_end"],
            rate=s["rate"], income_in_slab=s["income_in_slab"],
            tax_in_slab=s["tax_in_slab"],
        )
        for s in slab_dicts
    ]

    return RegimeTaxResult(
        regime="new", gross_salary=inp.annual_salary,
        standard_deduction=std, hra_exemption=0,
        deduction_80c=0, deduction_80ccd1b=0,
        deduction_80d_self=0, deduction_80d_parents=0,
        deduction_home_loan=0, total_deductions=std,
        taxable_income=taxable, slab_details=slab_details,
        gross_tax=gross_tax, rebate_87a=rebate,
        tax_after_rebate=tax_ar, surcharge_rate=s_rate,
        surcharge=surcharge, marginal_relief=relief,
        surcharge_after_relief=surcharge, cess=cess, final_tax=final,
        notes=["LLM-compiled rule execution", "New regime: only standard deduction"],
    )


class LLMCompiledTaxEngine:
    """
    Tax engine using LLM-compiled (pre-generated) Python rules.
    No LLM calls at runtime — deterministic and fast.
    """

    def compute(self, inp: TaxInput) -> TaxResult:
        old = _llm_gen_old_regime(inp)
        new = _llm_gen_new_regime(inp)

        if old.final_tax <= new.final_tax:
            recommended = "old"
            savings = new.final_tax - old.final_tax
            reason = (
                f"Old regime saves ₹{savings:,} via deductions "
                f"(80C: ₹{old.deduction_80c:,}, HRA: ₹{old.hra_exemption:,}, "
                f"80D: ₹{old.deduction_80d_self + old.deduction_80d_parents:,})"
            )
        else:
            recommended = "new"
            savings = old.final_tax - new.final_tax
            reason = (
                f"New regime saves ₹{savings:,}; deductions under old regime "
                f"(₹{old.total_deductions:,}) do not outweigh the lower slab rates."
            )

        return TaxResult(
            old_regime=old, new_regime=new,
            recommended_regime=recommended,
            savings=savings,
            recommendation_reason=reason,
        )

    def compute_dict(self, **kwargs) -> dict:
        inp = TaxInput(**kwargs)
        result = self.compute(inp)
        return _result_to_dict(result)


def _load_env_key() -> str:
    key = os.environ.get("GOOGLE_API_KEY", "")
    if not key:
        env_file = os.path.join(os.path.dirname(os.path.dirname(_current_dir)), ".env")
        if os.path.exists(env_file):
            with open(env_file, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line.startswith("GOOGLE_API_KEY="):
                        key = line.split("=", 1)[1].strip().strip('"').strip("'")
                        os.environ["GOOGLE_API_KEY"] = key
                        break
    return key


def compile_rules() -> str:
    """
    Demonstrates how to use an LLM to generate the compiled rules once.
    Returns the generated Python code as a string.
    Call this offline to regenerate the compiled rules.
    """
    api_key = _load_env_key()
    if not api_key:
        raise EnvironmentError("GOOGLE_API_KEY not set")

    try:
        import google.generativeai as genai
        genai.configure(api_key=api_key)
        model = genai.GenerativeModel("gemini-2.5-flash")
    except ImportError:
        raise ImportError("google-generativeai package not installed")

    prompt = """
You are a Python developer. Generate complete, correct Python functions that compute
Indian income tax for salaried individuals under FY 2024-25 rules.

Old regime slabs: 0-2.5L=0%, 2.5-5L=5%, 5-10L=20%, >10L=30%
New regime slabs: 0-3L=0%, 3-7L=5%, 7-10L=10%, 10-12L=15%, 12-15L=20%, >15L=30%
Standard deduction: old=50000, new=75000
87A rebate: old=12500 if taxable<=500000; new=25000 if taxable<=700000
Surcharge: 10% for 50L-1Cr, 15% for 1Cr-2Cr, 25% for 2Cr-5Cr, 37% for >5Cr (new capped at 25%)
Marginal relief applies
Cess: 4% on (tax+surcharge-rebate)
HRA: min(HRA received, rent-10%basic, 50%basic metro/40% non-metro)
80C cap 150000, 80CCD1B cap 50000, 80D self 25000/50000, parents 25000/50000, home loan 200000

Generate the functions as pure Python with no external dependencies.
Return ONLY valid Python code, no markdown.
"""

    response = model.generate_content(prompt, generation_config=genai.types.GenerationConfig(temperature=0))
    return response.text


